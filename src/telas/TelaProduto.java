    private void cadastrarBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cadastrarBtnActionPerformed
        // TODO add your handling code here:
        try {
            //Valida descrição
            String descricao = descricaoTxt.getText();
            if (descricaoTxt == null || descricao.trim().isEmpty()){
                mensagemTxt.setText("Erro: a descrição não pode estar vazia");
                return;
            }
            
            //Valida preço
            String precoStr = precoTxt.getText();
            if (precoStr == null || precoStr.trim().isEmpty()) {
                mensagemTxt.setText("Erro: o preço não pode estar vazio");
                return;
            }
        
            //Cadastra o produto
            String upDescricaoTxt = descricaoTxt.getText().toUpperCase();
            p.setDescricao(upDescricaoTxt);
            p.setPreco(Double.parseDouble(precoTxt.getText()));
            p.cadastrar();
            
            mensagemTxt.setText("");
            mensagemTxt.setText("Cadastrado com sucesso");
            
        //Exceptions
        } catch (SQLException | ClassNotFoundException ex) {
            mensagemTxt.setText("");
            
            mensagemTxt.setText("Erro: " + ex.getMessage());
        } catch (NumberFormatException ex){
            mensagemTxt.setText("");
            mensagemTxt.setText("Erro: Preço inválido.");
        } catch (Exception ex) {
            mensagemTxt.setText("Erro inesperado: " + ex.getMessage()); //Erros inesperados
        }
    }//GEN-LAST:event_cadastrarBtnActionPerformed

    private void deletarBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deletarBtnActionPerformed
        // TODO add your handling code here:
        try{
            //Deleta o produto
            p.setId(Integer.parseInt(idTxt.getText()));
            boolean deletado = p.deletar();
            //Limpa os campos dos textos
            descricaoTxt.setText("");
            precoTxt.setText("");
            mensagemTxt.setText("");
            
            //Verifica se foi deletado
            
            if (deletado) {
                mensagemTxt.setText("Deletado com sucesso");
            } else {
                mensagemTxt.setText("ID não encontrado. Nenhum registro foi deletado.");
            }
            
        //Exceptions
        }catch(SQLException | ClassNotFoundException ex){
            //Limpa campos
            mensagemTxt.setText("");
            
            mensagemTxt.setText("Erro: " + ex.getMessage());
        } catch (NumberFormatException ex){
            //Limpa campos
            mensagemTxt.setText("");
            mensagemTxt.setText("Erro: ID inválido.");
        } catch (Exception ex) {
            mensagemTxt.setText("Erro inesperado: " + ex.getMessage()); //Erros inesperados
        }
    }//GEN-LAST:event_deletarBtnActionPerformed

    private void atualizarBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_atualizarBtnActionPerformed
        // TODO add your handling code here:
        try {
            //Atualiza um produto
            p.setId(Integer.parseInt(idTxt.getText()));
            String upDescricaoTxt = descricaoTxt.getText().toUpperCase();
            p.setDescricao(upDescricaoTxt);
            p.setPreco(Double.parseDouble(precoTxt.getText()));
            
            //Verifica se a descrição está vazia
            String descricao = descricaoTxt.getText();
            if (descricaoTxt == null || descricao.trim().isEmpty()){
                mensagemTxt.setText("Erro: a descrição não pode estar vazia");
                return;
            }
            p.atualizar();
            
            //Limpa o campo de texto da mensagem
            mensagemTxt.setText("");
            
            //verifica se algo foi atualizado
            boolean atualizado = p.atualizar();
            if (atualizado) {
                mensagemTxt.setText("Atualizado com sucesso");
            } else {
                mensagemTxt.setText("ID não encontrado. Nenhum registro foi atualizado.");
            }
        
        //Exeptions
        } catch (SQLException | ClassNotFoundException ex) {
            //Limpa campos
            mensagemTxt.setText("");
            mensagemTxt.setText("Erro: " + ex.getMessage());
        } catch (NumberFormatException ex){
            //Limpa campos
            mensagemTxt.setText("");
            mensagemTxt.setText("Erro: Preço inválido.");
        } catch (Exception ex) {
            mensagemTxt.setText("Erro inesperado: " + ex.getMessage()); //Erros inesperados
        }
    }//GEN-LAST:event_atualizarBtnActionPerformed

