    private void configurarTabela() {
    //Evita que o Swing redimensione automaticamente
    tabelaTbl.setAutoResizeMode(JTable.AUTO_RESIZE_OFF);

    //Ajusta largura das colunas
    tabelaTbl.getColumnModel().getColumn(0).setPreferredWidth(25);   // ID
    tabelaTbl.getColumnModel().getColumn(1).setPreferredWidth(150);  // Descrição
    tabelaTbl.getColumnModel().getColumn(2).setPreferredWidth(55);   // Preço
    }
    
    private void consultartodosBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_consultartodosBtnActionPerformed
        // TODO add your handling code here:
        try {
            List<Produto> lprod = p.consultarTodos();

            //Define colunas
            String[] colunas = {"ID", "Descrição", "Preço"};
            DefaultTableModel modelo = new DefaultTableModel(colunas, 0);

            // Adiciona cada produto como uma linha
            for (Produto prod : lprod) {
                Object[] linha = {
                    prod.getId(),
                    prod.getDescricao(),
                    prod.getPreco()
                };
                modelo.addRow(linha);
            }

            //Atualiza a tabela
            tabelaTbl.setModel(modelo);
            tabelaTbl.getColumnModel().getColumn(0).setPreferredWidth(25);   // ID
            tabelaTbl.getColumnModel().getColumn(1).setPreferredWidth(150);  // Descrição
            tabelaTbl.getColumnModel().getColumn(2).setPreferredWidth(55);   // Preço
            
            } catch (SQLException | ClassNotFoundException ex) {
                mensagemTxt.setText("Erro: " + ex.getMessage());
            } catch (Exception ex) {
                mensagemTxt.setText("Erro inesperado: " + ex.getMessage());
            }       
    }//GEN-LAST:event_consultartodosBtnActionPerformed

